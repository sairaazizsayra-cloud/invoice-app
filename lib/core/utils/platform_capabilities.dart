import 'package:flutter/foundation.dart';

/// Plugin availability that cannot be inferred from `kIsWeb` alone.
class PlatformCapabilities {
  PlatformCapabilities._();

  static bool get crashlytics {
    if (kIsWeb) return false;
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
      case TargetPlatform.iOS:
      case TargetPlatform.macOS:
        return true;
      default:
        return false;
    }
  }

  static bool get pushMessaging {
    if (kIsWeb) return true;
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
      case TargetPlatform.iOS:
      case TargetPlatform.macOS:
        return true;
      default:
        return false;
    }
  }

  static bool get appCheck {
    if (kIsWeb) return true;
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
      case TargetPlatform.iOS:
      case TargetPlatform.macOS:
        return true;
      case TargetPlatform.windows:
        return false;
      default:
        return false;
    }
  }

  static bool get localFileSave => !kIsWeb;
}
